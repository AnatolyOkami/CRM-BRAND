create table public.configuration (
    id integer not null default 1 primary key,
    config jsonb not null default '{}'::jsonb,
    constraint configuration_singleton check (id = 1)
);

create table public.favicons_excluded_domains (
    id bigint generated by default as identity primary key,
    domain text not null
);

create table public.user_invitations (
    user_id uuid primary key
);

-- Working roles. A person may combine roles. No role means no business data.
create table public.staff_roles (
    -- react-admin identifies every record by id; (sales_id, role) stays the real key
    id bigint generated by default as identity not null unique,
    sales_id bigint not null,
    role text not null,
    created_at timestamp with time zone not null default now(),
    primary key (sales_id, role),
    constraint staff_roles_role_check check (role in ('manager', 'sales_head', 'production_head', 'workshop', 'fulfillment'))
);

-- Company-wide calendar used to compute the first reply deadline (singleton)
create table public.business_settings (
    id integer not null default 1 primary key,
    timezone text not null default 'Europe/Moscow',
    -- ISO weekdays: 1 = Monday ... 7 = Sunday
    work_days smallint[] not null default '{1,2,3,4,5}',
    work_start time without time zone not null default '09:00',
    work_end time without time zone not null default '18:00',
    first_response_minutes integer not null default 30,
    constraint business_settings_singleton check (id = 1),
    constraint business_settings_hours check (work_end > work_start),
    constraint business_settings_minutes check (first_response_minutes > 0)
);

-- Audit trail of ownership and stage changes made by the deal commands
create table public.deal_stage_history (
    id bigint generated by default as identity primary key,
    deal_id bigint not null,
    event text not null,
    from_stage text,
    to_stage text,
    from_sales_id bigint,
    to_sales_id bigint,
    changed_by bigint,
    reason text,
    created_at timestamp with time zone not null default now(),
    constraint deal_stage_history_event_check check (event in ('created', 'claimed', 'stage', 'assigned', 'released', 'call', 'source'))
);

-- Idempotency log of deal commands, never exposed through the Data API
create table private.deal_commands (
    user_id uuid not null,
    request_key text not null,
    command text not null,
    deal_id bigint,
    result jsonb not null,
    created_at timestamp with time zone not null default now(),
    primary key (user_id, request_key)
);

-- Production orders: one order per deal, created by the handoff command only
create table public.production_orders (
    id bigint generated by default as identity primary key,
    deal_id bigint not null unique,
    -- accepted -> in-progress -> ready (a ready order can go back to in-progress)
    stage text not null default 'accepted',
    product_name text not null,
    instructions text,
    due_date date,
    -- The customer in the volume the workshop needs: a name, never contacts or prices
    customer_name text not null default '',
    files_count integer not null default 0,
    links_count integer not null default 0,
    version integer not null default 1,
    -- Counts how many times the order became ready: one notification per cycle
    ready_cycle integer not null default 0,
    ready_at timestamp with time zone,
    ready_by bigint,
    handed_off_by bigint,
    created_at timestamp with time zone not null default now(),
    updated_at timestamp with time zone not null default now(),
    constraint production_orders_stage_check check (stage in ('accepted', 'in-progress', 'ready'))
);

-- Files (private storage objects) and links of an order
create table public.production_order_materials (
    id bigint generated by default as identity primary key,
    order_id bigint not null,
    kind text not null,
    label text,
    url text,
    file_path text,
    file_name text,
    file_size bigint,
    mime_type text,
    created_at timestamp with time zone not null default now(),
    constraint production_order_materials_kind_check check (kind in ('file', 'link')),
    constraint production_order_materials_shape check (
        (kind = 'link' and url ~ '^https?://[^[:space:]]+$' and file_path is null)
        or (kind = 'file' and file_path is not null and url is null)
    )
);

create table public.order_stage_history (
    id bigint generated by default as identity primary key,
    order_id bigint not null,
    event text not null,
    from_stage text,
    to_stage text,
    changed_by bigint,
    created_at timestamp with time zone not null default now(),
    constraint order_stage_history_event_check check (event in ('created', 'stage'))
);

-- Personal notifications, stored until the person confirms them
create table public.notification_events (
    id bigint generated by default as identity primary key,
    recipient_sales_id bigint not null,
    kind text not null,
    order_id bigint not null,
    deal_id bigint not null,
    ready_cycle integer not null,
    payload jsonb not null default '{}'::jsonb,
    created_at timestamp with time zone not null default now(),
    opened_at timestamp with time zone,
    acknowledged_at timestamp with time zone,
    acknowledged_by bigint,
    constraint notification_events_kind_check check (kind in ('order_ready')),
    constraint notification_events_one_per_event unique (order_id, ready_cycle, kind)
);

-- Payments and refunds of a deal, in whole rubles like deals.amount. Corrections are new rows.
create table public.deal_payments (
    id bigint generated by default as identity primary key,
    deal_id bigint not null,
    -- A refund is its own operation: it lowers the paid amount, it never edits a payment
    kind text not null,
    amount bigint not null,
    paid_at date not null default current_date,
    comment text,
    currency text not null default 'RUB',
    created_by bigint,
    created_at timestamp with time zone not null default now(),
    constraint deal_payments_kind_check check (kind in ('payment', 'refund')),
    constraint deal_payments_amount_check check (amount > 0 and amount <= 1000000000)
);

