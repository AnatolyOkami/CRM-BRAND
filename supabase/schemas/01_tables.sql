--
-- Tables
-- This file declares all tables in the public schema.
--

-- Extensions
create extension if not exists "http" with schema "extensions";
create extension if not exists "citext" with schema "extensions";

-- Private schema (used by sales policies migration)
create schema if not exists "private";

create table public.companies (
    id bigint generated by default as identity primary key,
    created_at timestamp with time zone not null default now(),
    name text not null,
    sector text,
    size smallint,
    linkedin_url text,
    website extensions.citext,
    phone_number text,
    address text,
    zipcode text,
    city text,
    state_abbr text,
    sales_id bigint,
    context_links json,
    country text,
    description text,
    revenue text,
    tax_identifier text,
    logo jsonb
);

create table public.contacts (
    id bigint generated by default as identity primary key,
    first_name text,
    last_name text,
    gender text,
    title text,
    background text,
    avatar jsonb,
    first_seen timestamp with time zone,
    last_seen timestamp with time zone,
    has_newsletter boolean,
    status text,
    tags bigint[],
    company_id bigint,
    sales_id bigint,
    linkedin_url text,
    email_jsonb jsonb,
    phone_jsonb jsonb
);

create table public.contact_notes (
    id bigint generated by default as identity (sequence name public."contactNotes_id_seq") not null,
    contact_id bigint not null,
    text text,
    date timestamp with time zone default now(),
    sales_id bigint,
    status text,
    attachments jsonb[]
);

create table public.deals (
    id bigint generated by default as identity primary key,
    name text not null,
    company_id bigint,
    contact_ids bigint[],
    categories text[],
    stage text not null,
    description text,
    amount bigint,
    created_at timestamp with time zone not null default now(),
    updated_at timestamp with time zone not null default now(),
    archived_at timestamp with time zone,
    expected_closing_date date,
    sales_id bigint,
    index smallint,
    -- Primary lead source and the real time of the first contact from the customer
    source text not null default 'manual',
    received_at timestamp with time zone not null default now(),
    -- First reply deadline (business hours) and the moment of the first meaningful reply
    first_response_due_at timestamp with time zone,
    first_responded_at timestamp with time zone,
    -- Optimistic lock used by the deal RPCs, bumped by a trigger on every update
    version integer not null default 1,
    lost_reason text,
    -- Deals imported from the past: allowed to exist in won without a production order
    is_historical boolean not null default false,
    -- Rejects implausible dates, e.g. typos such as 5-digit years, plus BC dates and infinity, which the UI cannot display
    constraint deals_expected_closing_date_range check (expected_closing_date between '1900-01-01' and '2900-12-31'),
    -- Stage codes are system codes: labels are configurable, codes are not
    constraint deals_stage_check check (stage in ('opportunity', 'to-contact', 'contacted', 'in-work', 'proposal-sent', 'in-negociation', 'won', 'lost', 'delayed')),
    constraint deals_source_check check (source in ('website', 'avito', 'telegram', 'whatsapp', 'phone', 'manual', 'other'))
);

create table public.deal_notes (
    id bigint generated by default as identity (sequence name public."dealNotes_id_seq") not null,
    deal_id bigint not null,
    type text,
    text text,
    date timestamp with time zone default now(),
    sales_id bigint,
    attachments jsonb[]
);

create table public.sales (
    id bigint generated by default as identity primary key,
    first_name text not null default 'Pending'::text,
    last_name text not null default 'Pending'::text,
    email extensions.citext not null,
    administrator boolean not null,
    user_id uuid not null,
    avatar jsonb,
    disabled boolean not null default false,
    secondary_emails jsonb not null default '[]'::jsonb,
    constraint sales_secondary_emails_is_array check (jsonb_typeof(secondary_emails) = 'array')
);

create unique index uq__sales__user_id on public.sales using btree (user_id);

create table public.tags (
    id bigint generated by default as identity primary key,
    name text not null,
    color text not null
);

create table public.tasks (
    id bigint generated by default as identity primary key,
    contact_id bigint not null,
    type text,
    text text,
    due_date timestamp with time zone,
    done_date timestamp with time zone,
    sales_id bigint,
    created_at timestamp with time zone not null default now(),
    -- Optional link to the deal the task belongs to (contact_id stays mandatory)
    deal_id bigint
);

create table public.configuration (
    id integer not null default 1 primary key,
    config jsonb not null default '{}'::jsonb,
    constraint configuration_singleton check (id = 1)
);

create table public.favicons_excluded_domains (
    id bigint generated by default as identity primary key,
    domain text not null
);

create table public.user_invitations (
    user_id uuid primary key
);

-- Working roles. A person may combine roles. No role means no business data.
create table public.staff_roles (
    sales_id bigint not null,
    role text not null,
    created_at timestamp with time zone not null default now(),
    primary key (sales_id, role),
    constraint staff_roles_role_check check (role in ('manager', 'sales_head', 'production_head', 'workshop', 'fulfillment'))
);

-- Company-wide calendar used to compute the first reply deadline (singleton)
create table public.business_settings (
    id integer not null default 1 primary key,
    timezone text not null default 'Europe/Moscow',
    -- ISO weekdays: 1 = Monday ... 7 = Sunday
    work_days smallint[] not null default '{1,2,3,4,5}',
    work_start time without time zone not null default '09:00',
    work_end time without time zone not null default '18:00',
    first_response_minutes integer not null default 30,
    constraint business_settings_singleton check (id = 1),
    constraint business_settings_hours check (work_end > work_start),
    constraint business_settings_minutes check (first_response_minutes > 0)
);

-- Audit trail of ownership and stage changes made by the deal commands
create table public.deal_stage_history (
    id bigint generated by default as identity primary key,
    deal_id bigint not null,
    event text not null,
    from_stage text,
    to_stage text,
    from_sales_id bigint,
    to_sales_id bigint,
    changed_by bigint,
    reason text,
    created_at timestamp with time zone not null default now(),
    constraint deal_stage_history_event_check check (event in ('created', 'claimed', 'stage', 'assigned', 'released'))
);

-- Idempotency log of deal commands, never exposed through the Data API
create table private.deal_commands (
    user_id uuid not null,
    request_key text not null,
    command text not null,
    deal_id bigint,
    result jsonb not null,
    created_at timestamp with time zone not null default now(),
    primary key (user_id, request_key)
);

