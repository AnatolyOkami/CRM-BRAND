    id bigint generated by default as identity primary key,
    created_at timestamp with time zone not null default now(),
    name text not null,
    sector text,
    size smallint,
    linkedin_url text,
    website extensions.citext,
    phone_number text,
    address text,
    zipcode text,
    city text,
    state_abbr text,
    sales_id bigint,
    context_links json,
    country text,
    description text,
    revenue text,
    tax_identifier text,
    logo jsonb
);

create table public.contacts (
    id bigint generated by default as identity primary key,
    first_name text,
    last_name text,
    gender text,
    title text,
    background text,
    avatar jsonb,
    first_seen timestamp with time zone,
    last_seen timestamp with time zone,
    has_newsletter boolean,
    status text,
    tags bigint[],
    company_id bigint,
    sales_id bigint,
    linkedin_url text,
    email_jsonb jsonb,
    phone_jsonb jsonb
);

create table public.contact_notes (
    id bigint generated by default as identity (sequence name public."contactNotes_id_seq") not null,
    contact_id bigint not null,
    text text,
    date timestamp with time zone default now(),
    sales_id bigint,
    status text,
    attachments jsonb[]
);

create table public.deals (
    id bigint generated by default as identity primary key,
    name text not null,
    company_id bigint,
    contact_ids bigint[],
    categories text[],
    stage text not null,
    description text,
    amount bigint,
    created_at timestamp with time zone not null default now(),
    updated_at timestamp with time zone not null default now(),
    archived_at timestamp with time zone,
    expected_closing_date date,
    sales_id bigint,
    index smallint,
    -- Primary lead source and the real time of the first contact from the customer
    source text not null default 'manual',
    received_at timestamp with time zone not null default now(),
    -- First reply deadline (business hours) and the moment of the first meaningful reply
    first_response_due_at timestamp with time zone,
    first_responded_at timestamp with time zone,
    -- Optimistic lock used by the deal RPCs, bumped by a trigger on every update
    version integer not null default 1,
    lost_reason text,
    -- Deals imported from the past: allowed to exist in won without a production order
    is_historical boolean not null default false,
    -- Signing of the contract: the date and, if there is one, a link to the document
    contract_signed_at date,
    contract_link text,
    -- Leads that arrive through a partner link or the website form: who sent it, the id of the submission
    -- (a repeated submission with the same id never creates a second deal) and the UTM labels
    partner_id bigint,
    intake_key text,
    utm jsonb,
    -- Rejects implausible dates, e.g. typos such as 5-digit years, plus BC dates and infinity, which the UI cannot display
    constraint deals_expected_closing_date_range check (expected_closing_date between '1900-01-01' and '2900-12-31'),
    -- Stage codes are system codes: labels are configurable, codes are not
    -- The pipeline is new (opportunity) -> processing -> order -> design (design-task, design-in-progress,
    -- design-ready) -> approval -> approved -> sent-to-production -> won, with lost on the side.
    -- proposal-sent, delayed, to-contact, contacted, in-work, in-negociation and contract-signed are retired:
    -- they stay valid only so that old history keeps its meaning, no deal enters them again.
    constraint deals_stage_check check (stage in ('opportunity', 'processing', 'order', 'design-task', 'design-in-progress', 'design-ready', 'approval', 'approved', 'sent-to-production', 'won', 'lost', 'proposal-sent', 'delayed', 'to-contact', 'contacted', 'in-work', 'in-negociation', 'contract-signed')),
    constraint deals_intake_key_check check (intake_key is null or (partner_id is not null and length(intake_key) between 8 and 100)),
    constraint deals_utm_is_object check (utm is null or jsonb_typeof(utm) = 'object')
);

-- Where the leads come from. The codes are system codes (stored on deals), the labels are editable.
-- Retired codes stay in the table so that old deals keep their label.
create table public.lead_sources (
    -- react-admin identifies every record by id; the code stays the real key
    id bigint generated by default as identity not null unique,
    code text primary key,
    label text not null,
    is_active boolean not null default true,
    position integer not null default 0,
    constraint lead_sources_code_check check (code ~ '^[a-z0-9][a-z0-9-]{0,39}$'),
    constraint lead_sources_label_check check (length(btrim(label)) between 1 and 80)
);

-- A way to send leads in: a link of an advertising partner (a public short form) or the website of the owner
-- (a request signed with a shared secret). The code in the link identifies the partner.
create table public.lead_partners (
    id bigint generated by default as identity primary key,
    name text not null,
    kind text not null default 'partner',
    source text not null,
    code text not null unique default encode(extensions.gen_random_bytes(12), 'hex'),
    is_active boolean not null default true,
    created_at timestamp with time zone not null default now(),
    constraint lead_partners_kind_check check (kind in ('partner', 'website')),
    constraint lead_partners_name_check check (length(btrim(name)) between 1 and 120)
);

-- Signing secrets of the website kind; never exposed through the Data API
create table private.lead_partner_secrets (
    partner_id bigint primary key,
    secret text not null
);

create table public.deal_notes (
    id bigint generated by default as identity (sequence name public."dealNotes_id_seq") not null,
    deal_id bigint not null,
    type text,
    text text,
    date timestamp with time zone default now(),
    sales_id bigint,
    attachments jsonb[]
);

create table public.sales (
    id bigint generated by default as identity primary key,
    first_name text not null default 'Pending'::text,
    last_name text not null default 'Pending'::text,
    email extensions.citext not null,
    administrator boolean not null,
    user_id uuid not null,
    avatar jsonb,
    disabled boolean not null default false,
    secondary_emails jsonb not null default '[]'::jsonb,
    constraint sales_secondary_emails_is_array check (jsonb_typeof(secondary_emails) = 'array')
);

create unique index uq__sales__user_id on public.sales using btree (user_id);

create table public.tags (
    id bigint generated by default as identity primary key,
    name text not null,
    color text not null
);

create table public.tasks (
    id bigint generated by default as identity primary key,
    contact_id bigint not null,
    type text,
    text text,
    due_date timestamp with time zone,
    done_date timestamp with time zone,
    sales_id bigint,
