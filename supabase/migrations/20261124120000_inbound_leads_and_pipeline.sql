-- Inbound leads and the new pipeline: partner links and website intake, sources of leads, the call result,
-- stages new -> processing -> order. Hand assembled from supabase/schemas.

-- Where the leads come from. The codes are system codes (stored on deals), the labels are editable.
-- Retired codes stay in the table so that old deals keep their label.
create table public.lead_sources (
    -- react-admin identifies every record by id; the code stays the real key
    id bigint generated by default as identity not null unique,
    code text primary key,
    label text not null,
    is_active boolean not null default true,
    position integer not null default 0,
    constraint lead_sources_code_check check (code ~ '^[a-z0-9][a-z0-9-]{0,39}$'),
    constraint lead_sources_label_check check (length(btrim(label)) between 1 and 80)
);

-- A way to send leads in: a link of an advertising partner (a public short form) or the website of the owner
-- (a request signed with a shared secret). The code in the link identifies the partner.
create table public.lead_partners (
    id bigint generated by default as identity primary key,
    name text not null,
    kind text not null default 'partner',
    source text not null,
    code text not null unique default encode(extensions.gen_random_bytes(12), 'hex'),
    is_active boolean not null default true,
    created_at timestamp with time zone not null default now(),
    constraint lead_partners_kind_check check (kind in ('partner', 'website')),
    constraint lead_partners_name_check check (length(btrim(name)) between 1 and 120)
);

-- Signing secrets of the website kind; never exposed through the Data API
create table private.lead_partner_secrets (
    partner_id bigint primary key,
    secret text not null
);

