-- Production handoff: two new stages, production orders with files and links, the workshop board
-- commands and the pinned notification of a ready order. Hand assembled from supabase/schemas.

alter table public.deals drop constraint deals_stage_check;
alter table public.deals
    add constraint deals_stage_check check (stage in ('opportunity', 'to-contact', 'contacted', 'in-work', 'proposal-sent', 'in-negociation', 'contract-signed', 'sent-to-production', 'won', 'lost', 'delayed'));
alter table public.deals
    add column contract_signed_at date,
    add column contract_link text;

-- Production orders: one order per deal, created by the handoff command only
create table public.production_orders (
    id bigint generated by default as identity primary key,
    deal_id bigint not null unique,
    -- accepted -> in-progress -> ready (a ready order can go back to in-progress)
    stage text not null default 'accepted',
    product_name text not null,
    instructions text,
    due_date date,
    -- The customer in the volume the workshop needs: a name, never contacts or prices
    customer_name text not null default '',
    files_count integer not null default 0,
    links_count integer not null default 0,
    version integer not null default 1,
    -- Counts how many times the order became ready: one notification per cycle
    ready_cycle integer not null default 0,
    ready_at timestamp with time zone,
    ready_by bigint,
    handed_off_by bigint,
    created_at timestamp with time zone not null default now(),
    updated_at timestamp with time zone not null default now(),
    constraint production_orders_stage_check check (stage in ('accepted', 'in-progress', 'ready'))
);

-- Files (private storage objects) and links of an order
create table public.production_order_materials (
    id bigint generated by default as identity primary key,
    order_id bigint not null,
    kind text not null,
    label text,
    url text,
    file_path text,
    file_name text,
    file_size bigint,
    mime_type text,
    created_at timestamp with time zone not null default now(),
    constraint production_order_materials_kind_check check (kind in ('file', 'link')),
    constraint production_order_materials_shape check (
        (kind = 'link' and url ~ '^https?://[^[:space:]]+$' and file_path is null)
        or (kind = 'file' and file_path is not null and url is null)
    )
);

create table public.order_stage_history (
    id bigint generated by default as identity primary key,
    order_id bigint not null,
    event text not null,
    from_stage text,
    to_stage text,
    changed_by bigint,
    created_at timestamp with time zone not null default now(),
    constraint order_stage_history_event_check check (event in ('created', 'stage'))
);

-- Personal notifications, stored until the person confirms them
create table public.notification_events (
    id bigint generated by default as identity primary key,
    recipient_sales_id bigint not null,
    kind text not null,
    order_id bigint not null,
    deal_id bigint not null,
    ready_cycle integer not null,
    payload jsonb not null default '{}'::jsonb,
    created_at timestamp with time zone not null default now(),
    opened_at timestamp with time zone,
    acknowledged_at timestamp with time zone,
    acknowledged_by bigint,
    constraint notification_events_kind_check check (kind in ('order_ready')),
    constraint notification_events_one_per_event unique (order_id, ready_cycle, kind)
);

